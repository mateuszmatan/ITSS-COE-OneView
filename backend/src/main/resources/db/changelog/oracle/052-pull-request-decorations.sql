-- The decorations of pull requests that the pipeline library reports to POST /api/dso/bitbucket/pull-requests/decorate
-- after it has commented on a pull request or opened one, and the findings of each decoration, which go with it.
-- PIPELINE_ID is the pipeline the run was found for, or null, like DSO_PIPELINE_REPORT.PIPELINE_ID; the pipeline key of
-- the run is not stored.
-- Each changeset holds one statement, because Oracle commits every DDL statement on its own: a statement that fails
-- leaves nothing of its changeset applied, and the next start runs the changeset again.

--changeset oneview:052-pr-decoration dbms:oracle,h2
CREATE TABLE DSO_PR_DECORATION (
    ID                          NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
    PIPELINE_ID                 NUMBER(19),
    RECORDED_AT                 TIMESTAMP       NOT NULL,
    JOB_NAME                    VARCHAR2(1000),
    BUILD_NUMBER                NUMBER(19),
    BRANCH                      VARCHAR2(500),
    COMMIT_HASH                 VARCHAR2(100),
    SERVICE_NAME                VARCHAR2(200),
    KIND                        VARCHAR2(20),
    REPOSITORY_URL              VARCHAR2(1000),
    PULL_REQUEST_ID             VARCHAR2(100)   NOT NULL,
    PULL_REQUEST_URL            VARCHAR2(2000),
    TITLE                       VARCHAR2(2000),
    SOURCE_BRANCH               VARCHAR2(500),
    TARGET_BRANCH               VARCHAR2(500),
    PULL_REQUEST_CREATED        NUMBER(1)       DEFAULT 0 NOT NULL,
    LINE_COMMENTS               NUMBER(10)      DEFAULT 0 NOT NULL,
    GENERAL_COMMENTS            NUMBER(10)      DEFAULT 0 NOT NULL,
    COMMENTS_LIMITED            NUMBER(1)       DEFAULT 0 NOT NULL,
    MAX_COMMENTS                NUMBER(10),
    FINDINGS_TOTAL              NUMBER(10)      DEFAULT 0 NOT NULL,
    SUMMARY                     CLOB,
    CONSTRAINT PK_DSO_PR_DECORATION PRIMARY KEY (ID),
    CONSTRAINT CK_DSO_PR_DECORATION_KIND CHECK (KIND IN ('BRANCH', 'STATIC', 'DAST')),
    CONSTRAINT CK_DSO_PR_DECORATION_FLAGS CHECK (PULL_REQUEST_CREATED IN (0, 1) AND COMMENTS_LIMITED IN (0, 1)),
    CONSTRAINT CK_DSO_PR_DECORATION_COUNTS CHECK (LINE_COMMENTS >= 0 AND GENERAL_COMMENTS >= 0
        AND FINDINGS_TOTAL >= 0 AND (MAX_COMMENTS IS NULL OR MAX_COMMENTS >= 0))
);
--rollback DROP TABLE DSO_PR_DECORATION;

--changeset oneview:052-pr-decoration-pipeline-index dbms:oracle,h2
CREATE INDEX IX_DSO_PR_DECORATION_PIPELINE ON DSO_PR_DECORATION (PIPELINE_ID, RECORDED_AT DESC);
--rollback DROP INDEX IX_DSO_PR_DECORATION_PIPELINE;

--changeset oneview:052-pr-decoration-finding dbms:oracle,h2
CREATE TABLE DSO_PR_DECORATION_FINDING (
    DECORATION_ID               NUMBER(19)      NOT NULL,
    POSITION                    NUMBER(10)      NOT NULL,
    TOOL                        VARCHAR2(100),
    SEVERITY                    VARCHAR2(50),
    FILE_PATH                   VARCHAR2(1000),
    LINE_NUMBER                 NUMBER(10),
    TITLE                       VARCHAR2(2000),
    DESCRIPTION                 VARCHAR2(4000),
    REMEDIATION                 VARCHAR2(4000),
    CONSTRAINT PK_DSO_PR_DECORATION_FINDING PRIMARY KEY (DECORATION_ID, POSITION),
    CONSTRAINT FK_DSO_PR_FINDING_DECORATION FOREIGN KEY (DECORATION_ID)
        REFERENCES DSO_PR_DECORATION (ID) ON DELETE CASCADE
);
--rollback DROP TABLE DSO_PR_DECORATION_FINDING;
