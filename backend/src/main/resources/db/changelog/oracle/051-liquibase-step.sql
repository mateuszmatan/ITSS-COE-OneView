-- 051-service-sonar-scanner-version and 051-service-sonar-scanner-version-copy keep FLUTTER_SONAR_SCANNER_VERSION,
-- which OneView no longer maps, so that the pod of the release before 051 keeps working while a rolling update starts
-- the new one; a later release drops it (TODO.md, item 3.9). Each changeset holds one statement, because Oracle commits
-- every DDL statement on its own: a statement that fails leaves nothing of its changeset applied, and the next start
-- runs the changeset again.

--changeset oneview:051-service-liquibase-step dbms:oracle,h2
ALTER TABLE DSO_SERVICE ADD (
    BUILD_LIQUIBASE_TASKS                       VARCHAR2(1000),
    BUILD_LIQUIBASE_FLAGS                       VARCHAR2(2000),
    BUILD_LIQUIBASE_DIRECTORY                   VARCHAR2(500),
    BUILD_LIQUIBASE_MAVEN_HOME                  VARCHAR2(500),
    BUILD_LIQUIBASE_ENVIRONMENT                 VARCHAR2(4000),
    BUILD_LIQUIBASE_LABEL                       VARCHAR2(200),
    BUILD_LIQUIBASE_RETURN_STDOUT               NUMBER(1) DEFAULT 0 NOT NULL,
    UNIT_TEST_LIQUIBASE_TASKS                   VARCHAR2(1000),
    UNIT_TEST_LIQUIBASE_FLAGS                   VARCHAR2(2000),
    UNIT_TEST_LIQUIBASE_DIRECTORY               VARCHAR2(500),
    UNIT_TEST_LIQUIBASE_MAVEN_HOME              VARCHAR2(500),
    UNIT_TEST_LIQUIBASE_ENVIRONMENT             VARCHAR2(4000),
    UNIT_TEST_LIQUIBASE_LABEL                   VARCHAR2(200),
    UNIT_TEST_LIQUIBASE_RETURN_STDOUT           NUMBER(1) DEFAULT 0 NOT NULL,
    APPSCAN_COMPILE_LIQUIBASE_TASKS             VARCHAR2(1000),
    APPSCAN_COMPILE_LIQUIBASE_FLAGS             VARCHAR2(2000),
    APPSCAN_COMPILE_LIQUIBASE_DIRECTORY         VARCHAR2(500),
    APPSCAN_COMPILE_LIQUIBASE_MAVEN_HOME        VARCHAR2(500),
    APPSCAN_COMPILE_LIQUIBASE_ENVIRONMENT       VARCHAR2(4000),
    APPSCAN_COMPILE_LIQUIBASE_LABEL             VARCHAR2(200),
    APPSCAN_COMPILE_LIQUIBASE_RETURN_STDOUT     NUMBER(1) DEFAULT 0 NOT NULL
);
--rollback ALTER TABLE DSO_SERVICE DROP (BUILD_LIQUIBASE_TASKS, BUILD_LIQUIBASE_FLAGS, BUILD_LIQUIBASE_DIRECTORY, BUILD_LIQUIBASE_MAVEN_HOME, BUILD_LIQUIBASE_ENVIRONMENT, BUILD_LIQUIBASE_LABEL, BUILD_LIQUIBASE_RETURN_STDOUT, UNIT_TEST_LIQUIBASE_TASKS, UNIT_TEST_LIQUIBASE_FLAGS, UNIT_TEST_LIQUIBASE_DIRECTORY, UNIT_TEST_LIQUIBASE_MAVEN_HOME, UNIT_TEST_LIQUIBASE_ENVIRONMENT, UNIT_TEST_LIQUIBASE_LABEL, UNIT_TEST_LIQUIBASE_RETURN_STDOUT, APPSCAN_COMPILE_LIQUIBASE_TASKS, APPSCAN_COMPILE_LIQUIBASE_FLAGS, APPSCAN_COMPILE_LIQUIBASE_DIRECTORY, APPSCAN_COMPILE_LIQUIBASE_MAVEN_HOME, APPSCAN_COMPILE_LIQUIBASE_ENVIRONMENT, APPSCAN_COMPILE_LIQUIBASE_LABEL, APPSCAN_COMPILE_LIQUIBASE_RETURN_STDOUT);

--changeset oneview:051-service-liquibase-step-check dbms:oracle,h2
ALTER TABLE DSO_SERVICE ADD CONSTRAINT CK_DSO_SERVICE_LIQUIBASE_STEP CHECK (BUILD_LIQUIBASE_RETURN_STDOUT IN (0, 1)
    AND UNIT_TEST_LIQUIBASE_RETURN_STDOUT IN (0, 1) AND APPSCAN_COMPILE_LIQUIBASE_RETURN_STDOUT IN (0, 1));
--rollback ALTER TABLE DSO_SERVICE DROP CONSTRAINT CK_DSO_SERVICE_LIQUIBASE_STEP;

